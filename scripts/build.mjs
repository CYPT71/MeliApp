import { cp, mkdir, rm, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import path from "node:path";

const root = process.cwd();
const out = path.join(root, "dist");
const entries = [
  "index.html",
  "manifest.webmanifest",
  "service-worker.js",
  "assets",
  "css",
  "js"
];

await rm(out, { recursive: true, force: true });
await mkdir(out, { recursive: true });

for (const entry of entries) {
  const source = path.join(root, entry);
  if (!existsSync(source)) throw new Error(`Build impossible : ${entry} est introuvable.`);
  await cp(source, path.join(out, entry), { recursive: true });
}

const microsoftClientId = String(process.env.MS_CLIENTID ?? "").trim();
const spotifyClientId = String(process.env.SPOTIFY_CLIENTID ?? "").trim();

if (microsoftClientId || spotifyClientId) {
  const content = `// Generated by scripts/build.mjs. Public OAuth client identifiers only.\nexport const config = Object.freeze({\n  microsoftClientId: ${JSON.stringify(microsoftClientId)},\n  microsoftTenant: "common",\n  microsoftAuthMode: "delegated",\n  microsoftScopes: Object.freeze(["openid", "profile", "offline_access", "Calendars.ReadWrite"]),\n  spotifyClientId: ${JSON.stringify(spotifyClientId)}\n});\n`;
  await writeFile(path.join(out, "js", "config.js"), content, "utf8");
}

console.log(`Build MeliApp prêt dans ${path.relative(root, out)}/`);
if (!microsoftClientId) console.log("Info: MS_CLIENTID absent, Outlook restera non configuré dans ce build.");
if (!spotifyClientId) console.log("Info: SPOTIFY_CLIENTID absent, Spotify restera non configuré dans ce build.");
